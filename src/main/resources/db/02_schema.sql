-- One table per D4/D5 domain class (9). Names: snake_case, plural; PK = <entity>_id (IDENTITY).
-- Booleans are NUMBER(1) 0/1; enums are VARCHAR2 holding the Java enum name(); dates are TIMESTAMP.
-- Reset: run 99_drop.sql, then 02_schema.sql and 03_seed.sql again.

CREATE TABLE workspaces (
    workspace_id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name               VARCHAR2(200) NOT NULL,
    target_industry            VARCHAR2(100),
    services_offered           VARCHAR2(1000),
    smtp_host                  VARCHAR2(200),
    smtp_port                  NUMBER(5),
    smtp_username              VARCHAR2(200),
    smtp_credential_encrypted  VARCHAR2(1000)
);

CREATE TABLE ideal_customer_profiles (
    icp_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id     NUMBER NOT NULL UNIQUE REFERENCES workspaces(workspace_id),
    target_industry  VARCHAR2(100) NOT NULL,
    criteria         VARCHAR2(1000) NOT NULL,
    generated_at     TIMESTAMP NOT NULL
);

CREATE TABLE api_call_logs (
    call_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id   NUMBER NOT NULL REFERENCES workspaces(workspace_id),
    provider_name  VARCHAR2(100) NOT NULL,
    operation      VARCHAR2(200) NOT NULL,
    status_code    NUMBER(3),
    error_message  VARCHAR2(1000),
    occurred_at    TIMESTAMP NOT NULL
);

CREATE TABLE users (
    user_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id   NUMBER NOT NULL REFERENCES workspaces(workspace_id),
    username       VARCHAR2(100) NOT NULL UNIQUE,
    password_hash  VARCHAR2(100) NOT NULL,
    role           VARCHAR2(20) NOT NULL CHECK (role IN ('ADMIN', 'SALES_REP')),
    is_active      NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0, 1))
);

CREATE TABLE leads (
    lead_id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id        NUMBER NOT NULL REFERENCES workspaces(workspace_id),
    created_by_user_id  NUMBER NOT NULL REFERENCES users(user_id),
    company_name        VARCHAR2(200) NOT NULL,
    industry            VARCHAR2(100),
    phone               VARCHAR2(50),
    status              VARCHAR2(20) DEFAULT 'DISCOVERED' NOT NULL
                        CHECK (status IN ('DISCOVERED', 'QUALIFIED', 'CONTACTED', 'CLOSED_WON', 'CLOSED_LOST')),
    is_archived         NUMBER(1) DEFAULT 0 NOT NULL CHECK (is_archived IN (0, 1)),
    created_at          TIMESTAMP NOT NULL
);

CREATE TABLE contacts (
    contact_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id     NUMBER NOT NULL REFERENCES leads(lead_id),
    full_name   VARCHAR2(200) NOT NULL,
    email       VARCHAR2(254) NOT NULL,
    job_role    VARCHAR2(100),
    phone       VARCHAR2(50)
);

CREATE TABLE interaction_logs (
    interaction_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id         NUMBER NOT NULL REFERENCES leads(lead_id),
    author_user_id  NUMBER NOT NULL REFERENCES users(user_id),
    note            VARCHAR2(4000) NOT NULL,
    created_at      TIMESTAMP NOT NULL
);

CREATE TABLE email_drafts (
    draft_id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id               NUMBER NOT NULL REFERENCES leads(lead_id),
    recipient_contact_id  NUMBER NOT NULL REFERENCES contacts(contact_id),
    subject               VARCHAR2(500) NOT NULL,
    body                  CLOB NOT NULL,
    status                VARCHAR2(20) NOT NULL CHECK (status IN ('DRAFT', 'APPROVED', 'SENT')),
    created_at            TIMESTAMP NOT NULL,
    approved_at           TIMESTAMP
);

CREATE TABLE outreach_dispatches (
    dispatch_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id              NUMBER NOT NULL REFERENCES email_drafts(draft_id),
    recipient_contact_id  NUMBER NOT NULL REFERENCES contacts(contact_id),
    sent_at               TIMESTAMP NOT NULL,
    delivery_status       VARCHAR2(20) NOT NULL CHECK (delivery_status IN ('SENT', 'FAILED')),
    error_message         VARCHAR2(1000)
);

CREATE INDEX idx_leads_ws_status ON leads (workspace_id, is_archived, status);
CREATE INDEX idx_contacts_lead ON contacts (lead_id);
CREATE INDEX idx_contacts_email ON contacts (LOWER(email));
CREATE INDEX idx_interactions_lead ON interaction_logs (lead_id);
CREATE INDEX idx_drafts_lead ON email_drafts (lead_id, status);
